"""Small ANSI terminal theme, with plain output for pipes and NO_COLOR."""

import builtins
import os
import shutil
import sys
import textwrap
import threading

STYLES = {"cyan": "96", "green": "92", "yellow": "93", "red": "91", "purple": "95",
          "blue": "94", "bold": "1", "dim": "2"}


def clean(value):
    # Names from Discord must not be able to inject terminal escape sequences.
    return "".join(character for character in str(value) if character in "\n\t" or (ord(character) >= 32 and not 127 <= ord(character) < 160))


class Console:
    def __init__(self, mode="auto"):
        self.mode = mode
        self._lock = threading.RLock()

    def enabled(self, stream=None):
        if self.mode == "always":
            return True
        if self.mode == "never" or "NO_COLOR" in os.environ:
            return False
        return os.environ.get("TERM") != "dumb" and (stream or sys.stdout).isatty()

    def paint(self, value, style, stream=None):
        text = clean(value)
        return f"\033[{STYLES[style]}m{text}\033[0m" if style and self.enabled(stream) else text

    def print(self, *values, sep=" ", end="\n", file=None, flush=False, style=None):
        text = sep.join(str(value) for value in values)
        if style is None:
            if text.startswith(("Error:", "Cannot ")):
                style = "red"
            elif text.startswith(("Warning:", "Waiting ", "Rate limited", "No usable", "No backups")):
                style = "yellow"
            elif text.startswith(("Saved", "Encrypted backup:", "Recovery page:", "Folder layout restored", "Favourite GIF settings restored")):
                style = "green"
            elif text.startswith(("Saving ", "Servers [", "Groups [", "Scanning ", "Checking ", "ETA for ", "Estimating ")):
                style = "cyan"
            elif text.startswith("Backing up "):
                style = "purple"
        with self._lock:
            builtins.print(self.paint(text, style, file), end=end, file=file, flush=flush)

    def input(self, prompt=""):
        return builtins.input(self.paint(prompt, "cyan"))

    def log(self, message):
        if message.startswith("Warning:"):
            width = max(40, min(120, shutil.get_terminal_size(fallback=(100, 24)).columns))
            message = textwrap.fill(clean(message), width=width, subsequent_indent="    ")
        self.print(message, flush=True)

    def banner(self, version, directory):
        self.print("\n  DISCORD BACKUP", style="bold")
        self.print(f"  Linux {version}  •  encrypted backups", style="purple")
        self.print("  " + "─" * 48, style="cyan")
        self.print(f"  Backups: {directory}", style="dim")

    def menu(self):
        self.print()
        options = [("1", "Back up account", "encrypted"), ("2", "Unlock / export recovery page", ""),
                   ("3", "Restore server folders", "preview first"), ("4", "Restore favourite GIF settings", "preview first"),
                   ("5", "List backups", ""), ("6", "Save token for scheduled backups", ""),
                   ("7", "Set up automatic backups", ""), ("8", "Save passphrase for scheduled backups", ""),
                   ("9", "Measure backup speed", "temporary backup, deleted afterward"), ("0", "Exit", "")]
        for number, label, detail in options:
            line = "  " + self.paint(f"[{number}]", "cyan") + "  " + clean(label)
            if detail:
                line += "  " + self.paint(detail, "dim")
            # These escape sequences were generated by paint, not remote content.
            builtins.print(line)
        self.print()

    def backup_summary(self, data):
        status = data["status"]
        self.print(f"\n  {status.upper()}  ·  {data['account']}", style="green" if status == "complete" else "yellow")
        for label, key in (("Servers", "guilds"), ("Friends", "friends"), ("Groups", "group-chats"), ("DM contacts", "dm-history")):
            self.print(f"  {label:<14} {data[key]}")
        if "duration_seconds" in data:
            self.print(f"  Time           {data['duration_seconds']:.2f}s", style="dim")
            self.print(f"  Discord waits  {data.get('cooldown_seconds', 0):.2f}s", style="dim")
        performance = data.get("performance", {})
        if performance:
            self.print(f"  HTTP requests  {performance['requests']}", style="dim")
            phases = performance.get("phase_seconds", {})
            if phases:
                phase = max(phases, key=phases.get)
                self.print(f"  Slowest stage  {phase} ({phases[phase]:.2f}s)", style="dim")
        if data.get("warnings"):
            width = max(40, min(120, shutil.get_terminal_size(fallback=(100, 24)).columns))
            self.print(f"\n  Warnings ({len(data['warnings'])})", style="yellow")
            affected = [key.replace("-", " ") + f" ({value})" for key, value in data.get("sections", {}).items()
                        if value in ("partial", "interrupted", "pending")]
            if affected:
                self.print(textwrap.fill("Sections needing attention: " + ", ".join(affected),
                           width=width, initial_indent="  ", subsequent_indent="    "), style="yellow")
            for warning in data["warnings"]:
                self.print(textwrap.fill(clean(warning), width=width, initial_indent="  • ",
                           subsequent_indent="    "), style="yellow")
            for instruction in ("Completed data is kept in the encrypted file. Unlock/export it to recover what was saved.",
                                "Missing data needs a new backup; rerunning does not resume this file."):
                self.print(textwrap.fill(instruction, width=width, initial_indent="  ", subsequent_indent="    "), style="dim")


console = Console()
